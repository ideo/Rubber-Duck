                    DispatchQueue.global().asyncAfter(deadline: .now() + .milliseconds(100)) {
                        finishTurnAfterDrain(utterance,
                                             track: track,
                                             generation: generation,
                                             startedWaitingAt: startedWaitingAt)
                    }
                    return
            }
        }

        log(String(format: "turns      %02d %@ %@ finished",
                   utterance.index, utterance.speaker, track.duck.rawValue))
        guard turnState.finish(generation: generation) else {
            return
        }
        let finishedIndex = turnState.currentIndex()
        guard finishedIndex < utterances.count - 1 else {
            log("turns      complete")
            return
        }
        DispatchQueue.global().asyncAfter(deadline: .now() + gapSec) {
            let snapshot = turnState.snapshot()
            guard snapshot.generation == generation else { return }
            let nextIndex = turnState.advance(delta: 1,
                                              maxIndex: utterances.count - 1)
            triggerTurn(utterances[nextIndex])
        }
    }

