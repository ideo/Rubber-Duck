final class PlaylistState: @unchecked Sendable {
    private let lock = NSLock()
    private var index: Int = 0
    private var playing: Bool = false
    private var generation: Int = 0
    private var remainingTracks: Int = 0
    private var startedAt: Date?

    func currentIndex() -> Int {
        lock.lock(); defer { lock.unlock() }
        return index
    }

    func snapshot() -> (index: Int, playing: Bool, generation: Int, startedAt: Date?) {
        lock.lock(); defer { lock.unlock() }
        return (index, playing, generation, startedAt)
    }

    func advance(delta: Int, maxIndex: Int) -> Int {
        lock.lock(); defer { lock.unlock() }
        index = min(max(index + delta, 0), maxIndex)
        playing = false
        remainingTracks = 0
        startedAt = nil
        generation += 1
        return index
    }

    func jump(to newIndex: Int, maxIndex: Int) -> Int {
        lock.lock(); defer { lock.unlock() }
        index = min(max(newIndex, 0), maxIndex)
        playing = false
        remainingTracks = 0
        startedAt = nil
        generation += 1
        return index
    }

    func start(trackCount: Int) -> Int {
        lock.lock(); defer { lock.unlock() }
        generation += 1
        remainingTracks = trackCount
        playing = trackCount > 0
        startedAt = playing ? Date() : nil
        return generation
    }

    func stop() {
        lock.lock(); defer { lock.unlock() }
        generation += 1
        remainingTracks = 0
        playing = false
        startedAt = nil
    }

    func finish(generation expectedGeneration: Int) -> Bool {
        lock.lock(); defer { lock.unlock() }
        guard generation == expectedGeneration else { return false }
        remainingTracks = max(remainingTracks - 1, 0)
        guard remainingTracks == 0 else { return false }
        playing = false
        startedAt = nil
        return true
    }
}

final class DuckGainStore: @unchecked Sendable {
    private let lock = NSLock()
    private var balances: [DuckID: Double]
    private var global: Double

    init(initial: [DuckID: Double]) {
        self.balances = initial
        self.global = 1.0
    }

    func get(_ duck: DuckID) -> Double {
        lock.lock(); defer { lock.unlock() }
        return global * (balances[duck] ?? 1.0)
    }

    func balance(_ duck: DuckID) -> Double {
        lock.lock(); defer { lock.unlock() }
        return balances[duck] ?? 1.0
    }

    func setBalance(_ duck: DuckID, _ value: Double) {
        lock.lock()
        balances[duck] = value
        lock.unlock()
    }

    func setGlobal(_ value: Double) {
        lock.lock()
        global = value
        lock.unlock()
    }

    func snapshot() -> (global: Double, balances: [DuckID: Double]) {
        lock.lock(); defer { lock.unlock() }
        return (global, balances)
    }
}

final class RecoveryMonitor: @unchecked Sendable {
    private let lock = NSLock()
    private var timer: DispatchSourceTimer?

    func replace(with newTimer: DispatchSourceTimer) {
        lock.lock()
        let oldTimer = timer
        timer = newTimer
        lock.unlock()
        oldTimer?.cancel()
        newTimer.resume()
    }

    func cancel() {
        lock.lock()
        let oldTimer = timer
        timer = nil
        lock.unlock()
        oldTimer?.cancel()
    }
}

final class DuckStatsTracker: @unchecked Sendable {
    struct Snapshot {
        let rxBps: Int
        let stalledSamples: Int
        let ageMs: Double
    }

    private struct Entry {
        var rxBps: Int = 0
        var stalledSamples: Int = 0
        var updatedAt: Date = .distantPast
    }

    private let lock = NSLock()
    private var entries: [DuckID: Entry] = [:]
    private let expectedRxBps = 32_000
    private let stalledRxBps = 12_000

    func reset(_ duck: DuckID) {
        lock.lock()
        entries[duck] = Entry()
        lock.unlock()
    }

    func noteText(duck: DuckID, text: String) {
        guard text.contains("\"type\":\"duck_stats\""),
              let data = text.data(using: .utf8),
              let json = try? JSONSerialization.jsonObject(with: data) as? [String: Any],
              let rx = json["rx_bps"] as? NSNumber else {
            return
        }

        let rxBps = rx.intValue
        lock.lock()
        var entry = entries[duck] ?? Entry()
        entry.rxBps = rxBps
        entry.updatedAt = Date()
        if rxBps < stalledRxBps {
            entry.stalledSamples += 1
        } else if rxBps > expectedRxBps / 2 {
            entry.stalledSamples = 0
        }
        entries[duck] = entry
        lock.unlock()
    }

    func stalledDucks(targets: [DuckID], playbackStartedAt: Date?,
                      minElapsedSec: TimeInterval = 4.0) -> [DuckID] {
        guard let playbackStartedAt,
              Date().timeIntervalSince(playbackStartedAt) >= minElapsedSec else {
            return []
        }

        lock.lock()
        let now = Date()
        let stalled = targets.filter { duck in
            guard let entry = entries[duck] else { return false }
            let ageMs = now.timeIntervalSince(entry.updatedAt) * 1000
            return ageMs <= 2_500 && entry.stalledSamples >= 2
        }
        lock.unlock()
        return stalled
    }
}

func jsonEscape(_ s: String) -> String {
    var out = ""
    for ch in s {
        switch ch {
        case "\\": out += "\\\\"
        case "\"": out += "\\\""
        case "\n": out += "\\n"
        case "\r": out += "\\r"
        case "\t": out += "\\t"
        default: out.append(ch)
        }
    }
    return out
}

func previewWords(_ s: String, maxWords: Int = 5) -> String {
    s.split(whereSeparator: { $0.isWhitespace })
        .prefix(maxWords)
        .joined(separator: " ")
}

// Resolve duck-map FIRST so the connect/disconnect logs can show names.
let duckMap: DuckMap? = {
    if args.noDuckMap { return nil }
    let path = args.duckMapPath ?? defaultDuckMapPath()
    guard let path else {
        log("duck-map    not found (production /ws/duck path disabled). " +
            "Use --duck-map FILE or --no-duck-map to silence this warning.")
        return nil
    }
    guard let map = DuckMap.load(from: path) else {
        fputs("fatal: --duck-map \(path) could not be loaded\n", stderr)
        exit(1)
    }
    let entries = map.allEntries
    log("duck-map    loaded \(path) — \(entries.count) entries")
    for e in entries {
        let nm = e.name.map { " \"\($0)\"" } ?? ""
        log("  \(e.duck.rawValue)\(nm) ← \(e.mac)")
    }
    return map
}()

let usbMap: USBDuckMap? = {
    guard let path = args.usbMapPath else { return nil }
    guard let map = USBDuckMap.load(from: path) else {
        fputs("fatal: --usb-map \(path) could not be loaded\n", stderr)
        exit(1)
    }
    log("usb-map     loaded \(path) — \(map.allEntries.count) entries")
    for e in map.allEntries {
        let nm = e.name.map { " \"\($0)\"" } ?? ""
        let dev = e.currentDevice ?? "(auto)"
        log("  \(e.duck.rawValue)\(nm) ← \(e.usbSerial ?? "no-serial") \(dev)")
    }
    return map
}()

// Label a connection as "D2 (Pekin)" when a name is known, else just "D2".
func label(_ duck: DuckID) -> String {
    if let n = duckMap?.name(for: duck) { return "\(duck.rawValue) (\(n))" }
    if let n = usbMap?.name(for: duck) { return "\(duck.rawValue) (\(n))" }
    return duck.rawValue
}

